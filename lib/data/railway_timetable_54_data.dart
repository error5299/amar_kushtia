class WesternRailwayTrain {
  final String trainNo;
  final String trainName;
  final String category; // 'আন্তঃনগর' | 'মেইল ও কমিউটার' | 'লোকাল ও শাটল'
  final String offDay; // e.g. "শুক্রবার", "মঙ্গলবার", "ছুটি নেই"
  final String originStation;
  final String departureTime24;
  final String departureTime12;
  final String destinationStation;
  final String arrivalTime24;
  final String arrivalTime12;
  final String? kushtiaPoradahStop;
  final List<String> routeStations;
  final String? routeDescription;
  final String? tableRef;

  const WesternRailwayTrain({
    required this.trainNo,
    required this.trainName,
    required this.category,
    required this.offDay,
    required this.originStation,
    required this.departureTime24,
    required this.departureTime12,
    required this.destinationStation,
    required this.arrivalTime24,
    required this.arrivalTime12,
    this.kushtiaPoradahStop,
    required this.routeStations,
    this.routeDescription,
    this.tableRef = 'টাইম টেবিল নং-৫৪ (১০.০৩.২০২৫)',
  });

  bool matchesRoute(String from, String to) {
    if (from == 'all' && to == 'all') return true;
    final normalizedStations = routeStations.map((s) => s.toLowerCase()).toList();
    
    if (from != 'all' && to != 'all') {
      final fromIdx = normalizedStations.indexWhere((s) => s.contains(from.toLowerCase()));
      final toIdx = normalizedStations.indexWhere((s) => s.contains(to.toLowerCase()));
      return fromIdx != -1 && toIdx != -1 && fromIdx < toIdx;
    }
    
    if (from != 'all') {
      return normalizedStations.any((s) => s.contains(from.toLowerCase()));
    }
    
    if (to != 'all') {
      return normalizedStations.any((s) => s.contains(to.toLowerCase()));
    }
    
    return true;
  }
}

